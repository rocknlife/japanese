export type VocabCategory = (typeof VOCAB_CATEGORIES)[number];

export interface VocabWord {
  id: string;
  kana: string;
  kanji?: string;
  romaji: string;
  koReading: string;
  meaning: string;
  category: VocabCategory;
}

type Row = [kana: string, kanji: string, romaji: string, koReading: string, meaning: string];

function make(category: VocabCategory, rows: Row[]): VocabWord[] {
  return rows.map(([kana, kanji, romaji, koReading, meaning], i) => ({
    id: `${category}-${i}`,
    kana,
    kanji: kanji || undefined,
    romaji,
    koReading,
    meaning,
    category,
  }));
}

